// Generates src/icons/sap-icons.generated.ts from the SAP icon SVG export.
// Usage: node scripts/generate-sap-icons.mjs <dir-with-Icons-and-SAP-icons.json>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const source = process.argv[2];
if (!source) throw new Error('Pass the folder that holds Icons/ and SAP-icons.json');

const meta = JSON.parse(readFileSync(join(source, 'SAP-icons.json'), 'utf8'));
const byName = new Map();
for (const [code, entry] of Object.entries(meta)) {
  entry.names.forEach((name, i) => byName.set(name.toLowerCase(), { code, rtl: entry.rtl, primary: i === 0, names: entry.names }));
}

const pascal = (name) => name.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const exportName = (name) => {
  const base = pascal(name);
  return `${/^\d/.test(base) ? 'Sap' + base : base}Icon`;
};

const files = readdirSync(join(source, 'Icons')).filter((f) => f.endsWith('.svg')).sort();
const catalog = [];
const catalogNames = new Set();
const addCatalog = (name, id, code) => {
  if (catalogNames.has(name)) return;
  catalogNames.add(name);
  catalog.push(`  '${name}': { icon: I.${id}${code ? `, code: ${code}` : ''} },`);
};
const lines = [];
const seen = new Set();
const aliases = [];
for (const file of files) {
  const name = file.slice(0, -4);
  const svg = readFileSync(join(source, 'Icons', file), 'utf8');
  const d = svg.match(/ d="([^"]+)"/)?.[1];
  if (!d || !/viewBox="0 0 16 16"/.test(svg)) throw new Error(`Unexpected SVG shape in ${file}`);
  const info = byName.get(name.toLowerCase());
  const id = exportName(name);
  if (seen.has(id)) throw new Error(`Duplicate export ${id}`);
  seen.add(id);
  const code = info ? `U+${info.code.slice(2).toUpperCase()}` : 'no code point';
  const flip = info?.rtl === 'flip';
  lines.push(`/** SAP icon \`${name}\` (${code}). */`);
  lines.push(`export const ${id} = /*#__PURE__*/ createSapIcon('${name}', '${d}'${flip ? ', true' : ''});`);
  addCatalog(name, id, info?.code);
  for (const alias of info?.names.slice(1) ?? []) aliases.push([alias, id]);
}
for (const [alias, target] of aliases) addCatalog(alias, target, byName.get(alias.toLowerCase())?.code);
for (const [alias, target] of aliases) {
  const id = exportName(alias);
  if (seen.has(id)) continue;
  seen.add(id);
  lines.push(`/** Alias of {@link ${target}} (SAP icon name \`${alias}\`). */`);
  lines.push(`export const ${id} = ${target};`);
}

const out = `// Generated by scripts/generate-sap-icons.mjs from the SAP icon SVG set. Do not edit by hand.
import { createSapIcon } from './createSapIcon';

${lines.join('\n')}
`;
writeFileSync(new URL('../src/icons/sap-icons.generated.ts', import.meta.url), out);

// Name → component and code point, for IconRegistry. Importing it pulls in every icon.
const catalogOut = `// Generated by scripts/generate-sap-icons.mjs. Do not edit by hand.
import * as I from './sap-icons.generated';
import type { SapIconComponent } from './createSapIcon';

/** Every SAP icon by name (aliases included), with its font code point when known. */
export const sapIconCatalog: Readonly<Record<string, { icon: SapIconComponent; code?: number }>> = {
${catalog.join('\n')}
};
`;
writeFileSync(new URL('../src/icons/sap-icon-catalog.generated.ts', import.meta.url), catalogOut);
console.log(`Wrote ${seen.size} icon exports`);
