import { expect, test, type Page } from '@playwright/test';
test.skip(({ isMobile }) => !!isMobile, 'Desktop layout');
const files = (page: Page) => page.getByRole('tree', { name: 'Project files' });
const item = (page: Page, name: RegExp) => files(page).getByRole('treeitem', { name });
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Create component' });
const GEN = ['QaCard.tsx', 'QaCard.css', 'QaCard.test.tsx', 'QaCard.docs.md', 'QaCard.example.tsx', 'index.ts'];
const re = (f: string) => new RegExp(`^${f.replace(/\./g, '\\.')}`);
test('QA: one Undo removes every generated file, one Redo restores them', async ({ page }) => {
  await page.addInitScript(() => { if (!sessionStorage.getItem('qa-undo')) { sessionStorage.setItem('qa-undo', '1'); indexedDB.deleteDatabase('eui-studio'); localStorage.clear(); } });
  await page.goto('/studio/');
  await page.getByRole('radio', { name: 'Code Studio' }).click();
  await expect(item(page, /^App\.tsx/)).toBeVisible();
  const before = (await files(page).getByRole('treeitem').allInnerTexts()).join('|');
  await item(page, /^src/).first().click({ button: 'right', position: { x: 30, y: 10 } });
  await page.getByRole('menuitem', { name: 'Create component…' }).click();
  await dialog(page).getByRole('textbox', { name: /Component name/ }).fill('QaCard');
  await dialog(page).getByRole('checkbox', { name: /Example \(/ }).check();
  await dialog(page).getByRole('button', { name: 'Create 6 files' }).click();
  await expect(dialog(page)).toBeHidden();
  for (const f of GEN) await expect(item(page, re(f)), f).toBeVisible();
  await page.screenshot({ path: 'test-results/qa-undo-1-created.png' });
  await page.getByRole('button', { name: /^Undo/ }).first().click();
  for (const f of GEN) await expect(item(page, re(f)), f).toHaveCount(0);
  await expect(item(page, /^QaCard$/)).toHaveCount(0);
  expect((await files(page).getByRole('treeitem').allInnerTexts()).join('|')).toBe(before);
  await expect(page.getByRole('list', { name: 'Open files' }).getByRole('button', { name: 'QaCard.tsx' })).toHaveCount(0);
  await page.screenshot({ path: 'test-results/qa-undo-2-undone.png' });
  await page.getByRole('button', { name: /^Redo/ }).first().click();
  for (const f of GEN) await expect(item(page, re(f)), f).toBeVisible();
  await page.screenshot({ path: 'test-results/qa-undo-3-redone.png' });
  await page.waitForTimeout(Number(process.env.QA_WAIT ?? 0));
  await page.reload();
  await page.getByRole('radio', { name: 'Code Studio' }).click().catch(() => {});
  for (const f of GEN) await expect(item(page, re(f)), `${f} after reload`).toBeVisible();
});
