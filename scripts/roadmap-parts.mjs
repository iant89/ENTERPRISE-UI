// The component roadmap lives in docs/roadmap/ as one file per top-level (`## `) section.
// Concatenating the parts in filename order (README.md excluded) reproduces the full roadmap byte-for-byte.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

export const ROADMAP_DIR = 'docs/roadmap';
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export function roadmapParts(dir = ROADMAP_DIR) {
  return readdirSync(dir).filter((f) => /^\d\d-.+\.md$/.test(f)).sort();
}

export function readRoadmap(dir = ROADMAP_DIR) {
  return roadmapParts(dir).map((f) => readFileSync(join(dir, f), 'utf8')).join('');
}

export function splitRoadmap(text) {
  const starts = [0, ...[...text.matchAll(/^## /gm)].map((m) => m.index).filter((i) => i > 0)];
  return starts.map((start, n) => {
    const chunk = text.slice(start, starts[n + 1] ?? text.length);
    const title = n === 0 ? 'introduction' : chunk.match(/^## (.+)$/m)[1];
    return { file: `${String(n).padStart(2, '0')}-${slug(title)}.md`, title: n === 0 ? 'Introduction' : title, chunk };
  });
}

export function writeRoadmap(text, dir = ROADMAP_DIR) {
  mkdirSync(dir, { recursive: true });
  for (const f of roadmapParts(dir)) rmSync(join(dir, f));
  const parts = splitRoadmap(text);
  for (const { file, chunk } of parts) writeFileSync(join(dir, file), chunk);
  const index = `# Component implementation roadmap\n\nThe roadmap is split into one file per top-level section. Read them in order; concatenating the numbered files (excluding this README) reproduces the full roadmap exactly.\n\nGenerated by \`scripts/generate-component-roadmap.mjs\`; don't edit the parts by hand.\n\n${parts.map(({ file, title }) => `- [${title}](${file})`).join('\n')}\n`;
  writeFileSync(join(dir, 'README.md'), index);
  return parts;
}
