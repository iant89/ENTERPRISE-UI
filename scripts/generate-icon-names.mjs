// Writes src/icons/icon-names.generated.ts: the IconName type, one entry per SVG in src/assets/icons plus the enterprise aliases.
// Run after adding or removing an icon file: node scripts/generate-icon-names.mjs
// (A unit test fails when the list and the folder are out of sync.)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/assets/icons/', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4).toLowerCase());
// Aliases of the enterprise collection (close, user, chevron-down…) are valid names too.
const aliases = Object.keys(JSON.parse(readFileSync(new URL('../src/icons/collections/enterprise/aliases.json', import.meta.url), 'utf8')));
const names = [...new Set([...files, ...aliases])].sort();
const out = `// Generated by scripts/generate-icon-names.mjs from src/assets/icons. Do not edit by hand.
// Type only: it adds nothing to the bundle.

/** Name of an icon in src/assets/icons, or an alias from src/icons/collections/enterprise/aliases.json. */
export type SapIconName =
${names.map((n) => `  | '${n}'`).join('\n')};
`;
writeFileSync(new URL('../src/icons/icon-names.generated.ts', import.meta.url), out);
console.log(`IconName: ${names.length} names`);
